# ----------------------------------------------------------------------------- model + data

def load_model(device=None, dtype=None):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    device = device or pick_device()
    dtype = dtype or pick_dtype(device)
    tok = AutoTokenizer.from_pretrained(MODEL_ID)
    tok.padding_side = "left"          # so index -1 is always the last real token
    try:                               # transformers >= 4.56 renamed torch_dtype -> dtype
        model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, dtype=dtype, attn_implementation="eager")
    except TypeError:
        model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, torch_dtype=dtype, attn_implementation="eager")
    model.to(device)                   # explicit .to() instead of device_map: works on MPS
    model.eval()
    return model, tok, dtype, device


def make_splits(seed=0, train_n=128, val_n=16, test_n=48):
    """Byte-identical to weeks 1-2: same source, same filter, same seed, same shuffle order."""
    from datasets import load_dataset
    adv = load_dataset("walledai/AdvBench", split="train")
    harmful = [x["prompt"] for x in adv]
