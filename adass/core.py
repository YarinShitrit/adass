# ----------------------------------------------------------------------------- device + dtype

def pick_device():
    if torch.cuda.is_available():
        return "cuda"
    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return "mps"
    return "cpu"


def pick_dtype(device):
    """Gemma-2 is bf16-native and can produce broken text in fp16.

    NOTE the trap this replaces: `torch.cuda.is_bf16_supported()` returns False (it does not
    raise) on a machine with no CUDA, so the week-1 expression silently selected float16 on
    Apple Silicon -- where bfloat16 is in fact supported. Weeks 1-2 ran bf16; matching that is
    also what makes the S1 replication gate meaningful.
    """
    if device == "cuda":
        return torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float32
    if device == "mps":
        return torch.bfloat16          # supported on MPS; do NOT fall back to fp16 here
    return torch.float32               # cpu


def empty_cache(device):
    if device == "cuda":
        torch.cuda.empty_cache()
    elif device == "mps":
        torch.mps.empty_cache()


DEFAULT_DEVICE = pick_device()                  # used as the default arg everywhere below
